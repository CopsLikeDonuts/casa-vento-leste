export const dictionaries: Record<Locale, Dict> = { pt, en, de }

export const intlLocale: Record<Locale, string> = { pt: 'pt-PT', en: 'en-GB', de: 'de-DE' }

export function formatEuro(locale: Locale, amount: number) {
  return new Intl.NumberFormat(intlLocale[locale], {
    style: 'currency',
    currency: 'EUR',
    maximumFractionDigits: 0,
  }).format(amount)
}

/** Bed type inside a sentence. German keeps the capital: nouns are capitalised. */
export function bedText(bed: string, locale: Locale) {
  return locale === 'de' ? bed : bed.charAt(0).toLowerCase() + bed.slice(1)
}
